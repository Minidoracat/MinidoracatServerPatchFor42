local applied = {} -- 已處理過的 ModelScript；同一個 Lua 環境重複呼叫不再 Load

-- 回傳 已設定數、白名單內但上游已改（static 或 mesh 不同）而跳過的數
local function apply()
    local sm = getScriptManager and getScriptManager()
    if not sm then return 0, 0 end
    local done, changed = 0, 0
    for full, mesh in pairs(LIST) do
        local ms = sm:getModelScript(full)
        if ms and not applied[ms] then
            applied[ms] = true
            local cur = ms:getMeshName()
            if ms:isStatic() or not cur or string.lower(cur) ~= string.lower(mesh) then
                changed = changed + 1
            elseif pcall(function() ms:Load(ms:getName(), "model " .. ms:getName() .. BODY) end) then
                done = done + 1
            else
                changed = changed + 1
            end
        end
    end
    return done, changed
end

local done, changed = apply()
if done + changed > 0 then
    print(PREFIX .. " +OPTIMIZE_GRAPH set on " .. done .. " vehicle model scripts"
        .. (changed > 0 and ("; " .. changed .. " skipped (changed upstream, re-run scripts/check_optimize_graph.py)") or ""))
end

-- 離線測試用（scripts/test_vehicle_optimize_graph.lua）；遊戲內不會有人引用
MSP_VehicleOptimizeGraph = { apply = apply, LIST = LIST }
